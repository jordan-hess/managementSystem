// Coprime with QUOTES.length (228 = 2²·3·19), so stepping by it visits every
// quote exactly once per cycle — and, unlike stepping by 1, doesn't walk
// through the list's same-author runs on consecutive days.
const DAY_STRIDE = 97

/**
 * The Home page's quote of the day — the same quote for everyone on a given
 * business-local (Africa/Johannesburg) calendar day, so a night-shift agent
 * and a day-shift agent see the same one until local midnight.
 */
export function getQuoteOfTheDay(now: Date = new Date()): Quote {
  const day = toBusinessLocalDate(now)
  const dayNumber = Math.floor(Date.UTC(day.getFullYear(), day.getMonth(), day.getDate()) / 86_400_000)
  return QUOTES[(dayNumber * DAY_STRIDE) % QUOTES.length]
}
